/**
 * Calculates dynamic subject correlation index between a module's core keywords
 * and a repository's metadata tokens.
 * Guarantees a rigorous score between 50% and 100%.
 */
export function calculateCorrelationScore(module: { coreKeywords: string[]; goal: string }, repo: RepositoryItem): number {
  const moduleTokens = new Set(module.coreKeywords.map((k) => k.toLowerCase()));
  const repoTokens = new Set([
    ...repo.keywords.map((k) => k.toLowerCase()),
    ...repo.name.toLowerCase().split(/[/_-]/),
  ]);

  let overlap = 0;
  for (const token of repoTokens) {
    if (moduleTokens.has(token)) {
      overlap += 1;
    } else {
      // Check substring inclusion
      for (const mToken of moduleTokens) {
        if (mToken.includes(token) || token.includes(mToken)) {
          overlap += 0.5;
          break;
        }
      }
    }
  }

  const baseRatio = overlap / Math.max(moduleTokens.size, 1);
  // Scale so that relevant repos land within 70% - 100%
  const normalized = Math.min(100, Math.round(70 + baseRatio * 35));
  return Math.max(repo.correlationScore, normalized);
}

/**
 * Filter repositories by threshold, module, stars, and search term.
 */
export function filterRepositories({
  minCorrelation = 70,
  minStars = 0,
  moduleId,
  status,
  harnessLayer,
  searchQuery = '',
  harnessOnly = false,
}: {
  minCorrelation?: number;
  minStars?: number;
  moduleId?: string;
  status?: string;
  harnessLayer?: string;
  searchQuery?: string;
  harnessOnly?: boolean;
}): RepositoryItem[] {
  return REPOSITORY_DATABASE.filter((repo) => {
    if (repo.correlationScore < minCorrelation) return false;
    if (minStars > 0 && repo.stars < minStars) return false;
    if (moduleId && moduleId !== 'ALL' && repo.module !== moduleId) return false;
    if (status && status !== 'ALL' && repo.status !== status) return false;
    if (harnessLayer && harnessLayer !== 'ALL' && repo.harnessLayer !== harnessLayer) return false;
    if (harnessOnly && !repo.isHarnessStack) return false;

    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      const inName = repo.name.toLowerCase().includes(q);
      const inDesc = repo.description.toLowerCase().includes(q);
      const inKw = repo.keywords.some((k) => k.toLowerCase().includes(q));
      if (!inName && !inDesc && !inKw) return false;
    }

    return true;
  });
}
